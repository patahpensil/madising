// Browser verification for WhatsApp OTP, passkeys, onboarding, settings and care team.
// Requires API and web started with the isolated fixture OTP sender and origin http://localhost:3000.
import assert from 'node:assert/strict';
import {randomInt} from 'node:crypto';
import {mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
const origin='http://localhost:3000';
const shots=process.env.SCREENSHOT_DIR;if(shots)mkdirSync(shots,{recursive:true});
const shot=async(page,name)=>{if(shots)await page.screenshot({path:`${shots}/${name}.png`,fullPage:false});};
const number=()=>`0899${String(randomInt(0,10**8)).padStart(8,'0')}`;
const browser=await chromium.launch({headless:true});
try{
 const ctx=await browser.newContext({viewport:{width:390,height:844}});
 const page=await ctx.newPage();
 const cdp=await ctx.newCDPSession(page);
 await cdp.send('WebAuthn.enable');
 await cdp.send('WebAuthn.addVirtualAuthenticator',{options:{protocol:'ctap2',transport:'internal',hasResidentKey:true,hasUserVerification:true,isUserVerified:true,automaticPresenceSimulation:true}});
 const button=name=>page.getByRole('button',{name,exact:true});
 await page.goto(origin+'/account');
 await shot(page,'01-login');
 await page.getByRole('tab',{name:'Daftar'}).click();
 await page.getByLabel('Nomor WhatsApp').fill('0212345678');
 await button('Kirim kode WhatsApp').click();
 await page.getByText('Masukkan nomor WhatsApp Indonesia yang valid').waitFor();
 const phone=number();
 await page.getByLabel('Nomor WhatsApp').fill(phone);
 await button('Kirim kode WhatsApp').click();
 await page.getByRole('heading',{name:'Masukkan kode verifikasi'}).waitFor();
 assert.match(await page.getByRole('button',{name:/Kirim ulang dalam \d+ detik/}).innerText(),/detik/);
 assert.equal(await page.getByRole('button',{name:/Kirim ulang dalam/}).isDisabled(),true);
 const code=(await page.locator('.fixture strong').innerText()).trim();
 assert.match(code,/^\d{6}$/);
 await shot(page,'02-otp');
 const wrong=String((Number(code)+1)%1e6).padStart(6,'0');
 await page.getByLabel('Digit 1').fill(wrong);
 await page.getByText('Sisa percobaan: 4').waitFor();
 await page.getByLabel('Digit 1').fill(code);
 await page.getByRole('dialog',{name:'Lindungi akun dengan passkey'}).waitFor();
 await shot(page,'03-passkey-offer');
 await button('Aktifkan passkey').click();
 await page.getByRole('dialog',{name:'Status kunjungan'}).waitFor();
 await shot(page,'04-tour-1');
 for(const title of ['Langkah berikutnya','Tim perawatan','Pengaturan']){await button('Lanjut').click();await page.getByRole('dialog',{name:title}).waitFor();}
 await shot(page,'05-tour-last');
 assert.equal(await button('Lewati').count(),0,'last step offers only Selesai');
 await button('Selesai').click();
 await page.reload();await page.getByRole('heading',{name:'Pasien',exact:true}).waitFor();
 await page.waitForTimeout(1500);
 assert.equal(await page.locator('.tour').count(),0,'guide does not repeat after completion');
 await button('Tim perawatan').click();
 await page.getByRole('heading',{name:'Belum ada petugas'}).waitFor();
 await shot(page,'06-care-team-empty');
 await button('Pengaturan').click();
 await shot(page,'07-settings');
 for(const label of ['Pusat Bantuan','Bahasa Aplikasi','Metode Pembayaran','Alamat Tersimpan','Masuk dengan Biometrik','Pengaturan dan Keamanan Akun','Pengaturan Notifikasi','Panduan Penggunaan','Keluar dari akun'])assert.equal(await page.getByRole('button',{name:label}).count(),1,label);
 await page.getByText(/Versi aplikasi/).waitFor();
 await button('Masuk dengan Biometrik').click();
 await page.getByText(/Passkey ditambahkan/).waitFor();
 await shot(page,'08-passkeys');
 await button('Pengaturan Notifikasi').click();
 const reminder=page.getByLabel('Pengingat jadwal');await reminder.uncheck();await page.waitForTimeout(500);
 await page.reload();await button('Pengaturan').click();await page.getByText(/WhatsApp ••••/).count();await button('Pengaturan Notifikasi').click();
 await page.waitForFunction(()=>document.querySelector('.toggle input')!==null);await page.waitForTimeout(800);
 assert.equal(await page.getByLabel('Pengingat jadwal').isChecked(),false,'notification preference persisted');
 await button('Panduan Penggunaan').click();
 await page.getByRole('dialog',{name:'Status kunjungan'}).waitFor();
 await page.keyboard.press('Escape');
 await button('Pengaturan').click();await button('Keluar dari akun').click();
 await page.getByRole('heading',{name:'Masuk ke MADISING'}).waitFor();
 await button('Masuk dengan passkey').click();
 await page.getByRole('heading',{name:'Pasien',exact:true}).waitFor();
 assert.equal(await page.getByRole('dialog',{name:'Lindungi akun dengan passkey'}).count(),0,'no offer after passkey login');
 const denied=await ctx.request.post(origin+'/account-api',{headers:{Origin:'https://evil.example','Content-Type':'application/json'},data:{operation:'care_team'}});
 assert.equal(denied.status(),403,'cross-origin request rejected');
 const other=await browser.newContext({viewport:{width:1280,height:800}});
 const anon=await other.request.post(origin+'/account-api',{headers:{Origin:origin,'Content-Type':'application/json'},data:{operation:'care_team'}});
 assert.equal(anon.status(),401,'care team requires a session');
 const desktop=await other.newPage();await desktop.goto(origin+'/account');await shot(desktop,'09-desktop-login');
 console.log('WhatsApp OTP, passkey enrolment and login, onboarding, settings and care team browser checks passed');
}finally{await browser.close();}
